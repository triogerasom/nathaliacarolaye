-- Casa & Obra V5.1 — backups automáticos versionados do estado compartilhado

create table if not exists public.app_state_backups (
  id bigint generated by default as identity primary key,
  state_id text not null,
  data jsonb not null,
  created_at timestamptz not null default now(),
  created_by uuid null
);

create index if not exists app_state_backups_state_created_idx
  on public.app_state_backups (state_id, created_at desc);

alter table public.app_state_backups enable row level security;
revoke all on table public.app_state_backups from anon;
grant select on table public.app_state_backups to authenticated;

drop policy if exists "app_state_backups_select_casa_obra" on public.app_state_backups;
create policy "app_state_backups_select_casa_obra"
on public.app_state_backups for select to authenticated
using (public.is_casa_obra_user());

create or replace function public.backup_casa_obra_state()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.data is distinct from new.data then
    if not exists (
      select 1 from public.app_state_backups
      where state_id = old.id
        and created_at >= now() - interval '1 hour'
    ) then
      insert into public.app_state_backups(state_id, data, created_by)
      values (old.id, old.data, old.updated_by);
    end if;

    delete from public.app_state_backups b
    where b.state_id = old.id
      and b.id not in (
        select id from public.app_state_backups
        where state_id = old.id
        order by created_at desc
        limit 240
      );
  end if;
  return new;
end;
$$;

drop trigger if exists trg_backup_casa_obra_state on public.app_state;
create trigger trg_backup_casa_obra_state
after update on public.app_state
for each row execute function public.backup_casa_obra_state();
